#!/usr/bin/env python3
"""Regenerate meerai-client/models.yml from the models.dev catalog.

Usage:
    python3 scripts/sync-models.py [--source PATH] [--output PATH]

The default source is downloaded from https://models.dev/api.json. The output
is checked in so the binary needs no network access. Each provider keeps at
most MAX_MODELS text models, newest first, with the newest model of every
FEATURED_FAMILY pinned. Reasoning tiers come from the model's `effort`
reasoning option, as the `low`, `medium`, `high`, `extrahigh`, and `max`
tiers that meerai exposes.
"""

from __future__ import annotations

import argparse
import json
import sys
import urllib.error
import urllib.request
from pathlib import Path

MODELS_DEV_URL = "https://models.dev/api.json"
# models.dev answers HTTP 403 to the default `Python-urllib/x.y` agent.
MODELS_DEV_USER_AGENT = "meerai-sync-models/1.0 (+https://meerai.packvision.xyz)"
MAX_MODELS = 50

# (meerai provider id, models.dev provider id)
PROVIDERS = [
    ("opencode-go", "opencode-go"),
    ("opencode", "opencode"),
    ("openrouter", "openrouter"),
    ("qwen-cloud", "alibaba-token-plan"),
    ("gemini", "google"),
    ("openai", "openai"),
    ("anthropic", "anthropic"),
    ("deepseek", "deepseek"),
    ("xai", "xai"),
    ("zai-coding", "zai"),
    ("moonshot", "moonshotai"),
    ("mistral", "mistral"),
]

# Usage data is not published as an open dataset. Keep one flagship per lab
# family so the gateway list holds the models people reach for, then fill the
# rest with the newest releases.
FEATURED_FAMILIES = {
    "openrouter": [
        "openai/",
        "anthropic/",
        "google/",
        "deepseek/",
        "x-ai/",
        "qwen/",
        "moonshotai/",
        "z-ai/",
        "meta-llama/",
        "mistralai/",
        "minimax/",
    ],
}

NON_CHAT_MARKERS = (
    "embed",
    "image",
    "tts",
    "whisper",
    "audio",
    "rerank",
    "moderation",
    "transcribe",
    "realtime",
    "guard",
    "safety",
    "ocr",
    "voice",
    "video",
    "voxtral",
)


def effort_levels(model: dict) -> list[str] | None:
    if not model.get("reasoning", False):
        return []
    values: set[str] = set()
    for option in model.get("reasoning_options") or []:
        if option.get("type") == "effort":
            values.update(option.get("values") or [])
    if not values:
        return None
    levels: list[str] = []
    if "low" in values:
        levels.append("low")
    if "medium" in values:
        levels.append("medium")
    if "high" in values:
        levels.append("high")
    if "xhigh" in values:
        levels.append("extrahigh")
    if "max" in values:
        levels.append("max")
    return levels


def is_chat_text(model: dict) -> bool:
    modalities = model.get("modalities") or {}
    if "text" not in (modalities.get("output") or []):
        return False
    haystack = f"{model.get('id', '')} {model.get('name', '')}".lower()
    return not any(marker in haystack for marker in NON_CHAT_MARKERS)


def release_key(model: dict):
    return (model.get("release_date") or "", model.get("last_updated") or "")


def pick_models(models: dict, families: list[str]) -> list[dict]:
    chat = [m for m in models.values() if is_chat_text(m)]
    chat.sort(key=release_key, reverse=True)
    if len(chat) <= MAX_MODELS:
        return chat

    pinned: list[dict] = []
    seen: set[str] = set()
    for prefix in families:
        for model in chat:
            if model["id"].startswith(prefix):
                if model["id"] not in seen:
                    pinned.append(model)
                    seen.add(model["id"])
                break

    for model in chat:
        if len(pinned) >= MAX_MODELS:
            break
        if model["id"] not in seen:
            pinned.append(model)
            seen.add(model["id"])

    order = {m["id"]: i for i, m in enumerate(chat)}
    pinned.sort(key=lambda m: order[m["id"]])
    return pinned[:MAX_MODELS]


def render(models: list[tuple[str, list[dict]]]) -> str:
    lines = [
        "# Generated by scripts/sync-models.py from https://models.dev/api.json.",
        "# Do not edit by hand: run the script and commit the result.",
        "models:",
    ]
    for provider, entries in models:
        for model in entries:
            lines.append(f"  - provider: {provider}")
            model_id = model["id"]
            lines.append(f"    id: '{model_id}'")
            context = (model.get("limit") or {}).get("context")
            if context:
                lines.append(f"    context_window: {context}")
            output = (model.get("limit") or {}).get("output")
            if output:
                lines.append(f"    max_output_tokens: {output}")
            cost = model.get("cost") or {}
            for key, field in (
                ("input", "input_cost_per_mtok"),
                ("output", "output_cost_per_mtok"),
            ):
                value = cost.get(key)
                if value is not None:
                    lines.append(f"    {field}: {value}")
            levels = effort_levels(model)
            if levels is not None:
                if levels:
                    lines.append(f"    effort_levels: [{', '.join(levels)}]")
                else:
                    lines.append("    effort_levels: []")
    return "\n".join(lines) + "\n"


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--source", type=Path, default=None)
    parser.add_argument(
        "--output",
        type=Path,
        default=Path(__file__).resolve().parent.parent / "meerai-client" / "models.yml",
    )
    args = parser.parse_args()

    if args.source is not None:
        raw = args.source.read_text()
    else:
        request = urllib.request.Request(
            MODELS_DEV_URL, headers={"User-Agent": MODELS_DEV_USER_AGENT}
        )
        try:
            with urllib.request.urlopen(request, timeout=60) as response:
                raw = response.read().decode()
        except urllib.error.HTTPError as err:
            print(
                f"cannot download {MODELS_DEV_URL}: HTTP {err.code}. "
                "Retry later, or download it yourself and pass --source PATH.",
                file=sys.stderr,
            )
            return 1
        except OSError as err:
            print(
                f"cannot download {MODELS_DEV_URL}: {err}. "
                "Download it yourself and pass --source PATH.",
                file=sys.stderr,
            )
            return 1
    catalog = json.loads(raw)

    rendered: list[tuple[str, list[dict]]] = []
    for provider, source in PROVIDERS:
        entry = catalog.get(source)
        if entry is None:
            print(f"missing models.dev provider: {source}", file=sys.stderr)
            return 1
        picked = pick_models(
            entry.get("models") or {}, FEATURED_FAMILIES.get(provider, [])
        )
        rendered.append((provider, picked))

    args.output.write_text(render(rendered))
    total = sum(len(entries) for _, entries in rendered)
    print(f"wrote {total} models for {len(rendered)} providers to {args.output}")
    for provider, entries in rendered:
        print(f"  {provider}: {len(entries)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
