pub(crate) fn is_keyword(language: Language, word: &str) -> bool {
    keywords(language).contains(&word)
}

fn comment_prefix(language: Language) -> &'static str {
    match language {
        Language::Python
        | Language::Bash
        | Language::Yaml
        | Language::Toml
        | Language::Ruby
        | Language::Markdown => "#",
        Language::Sql | Language::Haskell => "--",
        _ => "//",
    }
}

fn tokenize(language: Language, line: &str) -> Vec<Token> {
    if line.is_empty() {
        return vec![Token {
            text: String::new(),
            kind: TokenKind::Plain,
        }];
    }
    let comment = comment_prefix(language);
    let mut out: Vec<Token> = Vec::new();
    let mut index = 0usize;

    while index < line.len() {
        let rest = &line[index..];
        let ch = rest.chars().next().unwrap_or(' ');
        if rest.starts_with(comment) {
            push_token(&mut out, rest, TokenKind::Comment);
            break;
        }
        if ch == '"' || ch == '\'' || ch == '`' {
            let mut end = index + ch.len_utf8();
            let mut escaped = false;
            let mut closed = false;
            for next in line[end..].chars() {
                end += next.len_utf8();
                if escaped {
                    escaped = false;
                } else if next == '\\' {
                    escaped = true;
                } else if next == ch {
                    closed = true;
                    break;
                }
            }
            let end = if closed { end } else { line.len() };
            push_token(&mut out, &line[index..end], TokenKind::String);
            index = end;
            continue;
        }
        if ch.is_ascii_digit() {
            let mut end = index + ch.len_utf8();
            for next in line[end..].chars() {
                if next.is_ascii_alphanumeric() || next == '_' || next == '.' {
                    end += next.len_utf8();
                } else {
                    break;
                }
            }
            push_token(&mut out, &line[index..end], TokenKind::Number);
            index = end;
            continue;
        }
        if ch.is_alphanumeric() || ch == '_' {
            let mut end = index + ch.len_utf8();
            for next in line[end..].chars() {
                if next.is_alphanumeric() || next == '_' {
                    end += next.len_utf8();
                } else {
                    break;
                }
            }
            let word = &line[index..end];
            let kind = if is_keyword(language, word) {
                TokenKind::Keyword
            } else if line[end..].trim_start().starts_with('(') {
                TokenKind::Function
            } else {
                TokenKind::Plain
            };
            push_token(&mut out, word, kind);
            index = end;
            continue;
        }
        push_token(
            &mut out,
            &line[index..index + ch.len_utf8()],
            TokenKind::Plain,
        );
        index += ch.len_utf8();
    }

    if out.is_empty() {
        out.push(Token {
            text: line.to_string(),
            kind: TokenKind::Plain,
        });
    }
    out
}

pub(crate) fn push_token(out: &mut Vec<Token>, text: &str, kind: TokenKind) {
    if let Some(last) = out.last_mut()
        && last.kind == kind
    {
        last.text.push_str(text);
        return;
    }
    out.push(Token {
        text: text.to_string(),
        kind,
    });
}
